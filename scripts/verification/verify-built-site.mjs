import assert from 'node:assert/strict';
import { mkdtemp, copyFile, rm, readFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';
import { createPortalServer } from '../../dist/server.mjs';
import { validateSiteContent } from '../../dist/lib/site-content.mjs';
import { feedbackDefaultMigrations, photoDefaultMigrations, migratePortalDefaults } from '../../dist/public/site-content-schema.js';
const rootDir = fileURLToPath(new URL('../../dist/', import.meta.url));
const dataDir = await mkdtemp(path.join(os.tmpdir(), 'yanyang-built-check-'));
let server, browser;
try {
  for (const name of ['articles.json', 'site-content.json']) await copyFile(path.join(rootDir, 'data', name), path.join(dataDir, name));
  server = await createPortalServer({ rootDir, dataDir, deploymentDir: path.join(dataDir, 'downloads') });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const base = 'http://127.0.0.1:' + server.address().port;
  const nextHtml = await (await fetch(base + '/')).text();
  assert.ok(nextHtml.includes('/_next/static/'), 'Portable build uses exported Next pages');
  const chunk = nextHtml.match(/src="([^"]*\/_next\/static\/[^"]+\.js)"/)[1];
  assert.equal((await fetch(base + chunk)).status, 200, 'Next runtime chunk is served');
  for (const route of ['/admin/', '/admin-site-content.js', '/admin-management.js', '/site-content-schema.js', '/app.js', '/portal-i18n.js']) assert.equal((await fetch(base + route)).status, 200, route);
  for (const code of ['zh-TW', 'en', 'ko', 'ja', 'de', 'fr', 'ru', 'es', 'ar', 'pt', 'it']) {
    const response = await fetch(base + `/locales/${code}.json`);
    assert.equal(response.status, 200, code);
    assert.match(response.headers.get('content-type'), /^application\/json/);
    const dictionary = await response.json();
    assert.equal(dictionary.locale, code);
    assert.ok(dictionary.values['nav.home']);
  }
  for (const route of ['/locales/admin.json', '/locales/unknown.json']) assert.equal((await fetch(base + route)).status, 404, route);
  const expected = migratePortalDefaults(validateSiteContent(JSON.parse(await readFile(path.join(rootDir, 'data/site-content.json'), 'utf8'))));
  for (const { key, previousValue, value } of [...feedbackDefaultMigrations, ...photoDefaultMigrations]) if (expected.values[key] === previousValue) expected.values[key] = value;
  assert.deepEqual((await (await fetch(base + '/api/site-content')).json()).content, expected);
  assert.equal((await (await fetch(base + '/api/admin/session')).json()).setupRequired, true);
  assert.equal((await fetch(base + '/data/site-content.json')).status, 404);
  const setup = await fetch(base + '/api/admin/setup', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ username: 'built_owner', password: 'built-owner-password-2026' }) });
  assert.equal(setup.status, 201);
  const owner = await setup.json(); assert.equal(owner.role, 'superadmin');
  const headers = { 'Content-Type': 'application/json', Cookie: setup.headers.get('set-cookie').split(';')[0], 'X-CSRF-Token': owner.csrfToken };
  const created = await fetch(base + '/api/admin/users', { method: 'POST', headers, body: JSON.stringify({ username: 'built_editor', password: 'built-editor-password-2026' }) });
  assert.equal(created.status, 201); const editor = (await created.json()).user; assert.equal(editor.role, 'admin');
  const seniorCreated = await fetch(base + '/api/admin/users', { method: 'POST', headers, body: JSON.stringify({ username: 'built_senior', password: 'built-senior-password-2026', role: 'senioradmin' }) });
  assert.equal(seniorCreated.status, 201); const seniorUser = (await seniorCreated.json()).user; assert.equal(seniorUser.role, 'senioradmin');
  const login = async (username, password) => {
    const response = await fetch(base + '/api/admin/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ username, password }) });
    assert.equal(response.status, 200); const account = await response.json();
    return { 'Content-Type': 'application/json', Cookie: response.headers.get('set-cookie').split(';')[0], 'X-CSRF-Token': account.csrfToken };
  };
  const seniorHeaders = await login('built_senior', 'built-senior-password-2026');
  for (const route of ['/api/admin/users', '/api/admin/logs', '/api/admin/site-content', '/api/admin/export']) assert.equal((await fetch(base + route, { headers: seniorHeaders })).status, 200, '高级管理员：' + route);
  assert.equal((await fetch(base + '/api/admin/users/' + editor.id, { method: 'PUT', headers: seniorHeaders, body: JSON.stringify({ role: 'senioradmin' }) })).status, 403);
  assert.equal((await fetch(base + '/api/admin/users/' + owner.userId, { method: 'PUT', headers: seniorHeaders, body: JSON.stringify({ disabled: true }) })).status, 403);
  assert.equal((await fetch(base + '/api/admin/users', { method: 'POST', headers: seniorHeaders, body: JSON.stringify({ username: 'built_forbidden', password: 'built-forbidden-password-2026', role: 'superadmin' }) })).status, 403);
  const editorHeaders = await login('built_editor', 'built-editor-password-2026');
  assert.equal((await fetch(base + '/api/admin/logs', { headers: editorHeaders })).status, 403);
  const application = await fetch(base + '/api/admin/articles', { method: 'POST', headers: editorHeaders, body: JSON.stringify({ title: '构建版高级管理员审批验证', category: '通知公告', date: '2026-10-11', body: ['隔离临时内容。'], status: 'published' }) });
  assert.equal(application.status, 202); const request = (await application.json()).request;
  assert.ok((await (await fetch(base + '/api/admin/requests', { headers: seniorHeaders })).json()).requests.some(item => item.id === request.id));
  assert.equal((await fetch(base + '/api/admin/requests/' + request.id + '/review', { method: 'POST', headers: seniorHeaders, body: JSON.stringify({ decision: 'approve' }) })).status, 200);
  for (const role of ['superadmin', 'senioradmin', 'admin']) assert.equal((await fetch(base + '/api/admin/users/' + seniorUser.id, { method: 'PUT', headers, body: JSON.stringify({ role }) })).status, 200, '超管调整等级：' + role);
  assert.equal((await fetch(base + '/api/admin/logs', { headers: seniorHeaders })).status, 401, '等级修改后撤销旧会话');
  const downgradedHeaders = await login('built_senior', 'built-senior-password-2026');
  assert.equal((await fetch(base + '/api/admin/logs', { headers: downgradedHeaders })).status, 403, '降级后普通权限');
  const feedback = await fetch(base + '/api/feedback', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ type: 'suggestion', gameName: 'BuiltCheckPlayer', qq: '765432109876', title: '构建版意见验证', content: '这是验证构建版反馈功能的临时内容。' }) });
  assert.equal(feedback.status, 201);
  const feedbackList = await (await fetch(base + '/api/admin/feedback', { headers })).json();
  assert.equal(feedbackList.total, 1); assert.equal(feedbackList.feedback[0].gameName, 'BuiltCheckPlayer'); assert.equal(feedbackList.feedback[0].qq, '765432109876');
  assert.ok((await (await fetch(base + '/api/admin/logs', { headers })).json()).logs.some(log => log.action === 'feedback.submit'));
  assert.ok((await (await fetch(base + '/api/admin/logs', { headers })).json()).logs.some(log => log.actor.role === 'senioradmin' && log.action === 'request.approve'));
  assert.equal((await fetch(base + '/data/feedback.json')).status, 404);
  const plan = await fetch(base + '/api/admin/articles', { method: 'POST', headers, body: JSON.stringify({ title: '构建版定时发布验证', category: '通知公告', date: '2026-10-11', body: ['临时验证正文。'], status: 'scheduled', scheduledAt: new Date(Date.now() + 1500).toISOString() }) });
  assert.equal(plan.status, 201);
  const planned = await plan.json();
  await new Promise(resolve => setTimeout(resolve, 2200));
  assert.ok((await (await fetch(base + '/api/articles')).json()).articles.some(article => article.id === planned.article.id));
  assert.equal((await (await fetch(base + '/api/admin/logs?action=article.auto_publish', { headers })).json()).total, 1);
  browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.goto(base + '/admin/');
  await page.locator('#username').fill('built_owner');
  await page.locator('#password').fill('built-owner-password-2026');
  await page.locator('#auth-submit').click();
  await page.locator('#workspace').waitFor({ state: 'visible', timeout: 15000 });
  assert.deepEqual(errors, [], 'Portable Next runtime has no JavaScript or CSP errors');
  console.log('构建服务、三种管理员等级与越权拦截、审批、会话撤销、真实反馈和定时发布日志验证通过（隔离数据）。');
} finally {
  await browser?.close();
  if (server) { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); }
  await rm(dataDir, { recursive: true, force: true });
}
